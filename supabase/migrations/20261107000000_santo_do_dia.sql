-- Santo do dia (calendário hagiológico): um texto para cada dia do ano,
-- igual em todos os anos. Leitura pública; secretaria e administrador editam.
-- Lista inicial importada de blog.comfebrasil.com.br/santo-do-dia-calendario-hagiologico
-- (o site não traz o dia 29 de fevereiro).

create table public.santos_do_dia (
  mes smallint not null check (mes between 1 and 12),
  dia smallint not null check (dia between 1 and 31),
  nome text not null check (length(trim(nome)) > 0),
  atualizado_em timestamptz not null default now(),
  primary key (mes, dia)
);

alter table public.santos_do_dia enable row level security;

create policy "todos veem o santo do dia" on public.santos_do_dia
  for select to anon, authenticated using (true);
create policy "equipe cadastra santo do dia" on public.santos_do_dia
  for insert to authenticated with check (public.eh_equipe());
create policy "equipe altera santo do dia" on public.santos_do_dia
  for update to authenticated using (public.eh_equipe()) with check (public.eh_equipe());
create policy "equipe remove santo do dia" on public.santos_do_dia
  for delete to authenticated using (public.eh_equipe());

